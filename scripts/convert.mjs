// Converts the original static HTML pages into React-ready fragments.
// Reads every *.html in the template root, strips <head>/<script>, rewrites
// relative "assets/..." paths to absolute "/assets/...", and writes:
//   src/pages/html/<name>.html   (body fragment, injected via dangerouslySetInnerHTML)
//   src/routes.js                (route manifest: path, file name, <title>)
// Re-runnable: `node scripts/convert.mjs` from anywhere.
import { readFileSync, writeFileSync, readdirSync, mkdirSync } from "fs";
import { fileURLToPath } from "url";
import { dirname, resolve, basename } from "path";

const __dirname = dirname(fileURLToPath(import.meta.url));
const SRC = resolve(__dirname, "..", "..");       // template root (the .html files)
const OUT = resolve(__dirname, "..", "src");
const HTML_OUT = resolve(OUT, "pages", "html");
mkdirSync(HTML_OUT, { recursive: true });

const files = readdirSync(SRC).filter((f) => f.endsWith(".html"));

const nameToPath = (name) => (name === "index" ? "/" : "/" + name);
const routes = [];

for (const file of files) {
  const name = basename(file, ".html");
  const raw = readFileSync(resolve(SRC, file), "utf8");

  const title = (raw.match(/<title>([\s\S]*?)<\/title>/i)?.[1] || name).trim();

  let body = raw.match(/<body[^>]*>([\s\S]*?)<\/body>/i)?.[1] ?? raw;
  body = body.replace(/<script[\s\S]*?<\/script>/gi, "");        // drop all scripts
  body = body.replace(/<!--\s*Mirrored from[\s\S]*?-->/gi, "");   // HTTrack noise
  body = body.replace(/(["'(])assets\//g, "$1/assets/");         // relative -> absolute assets
  body = body.trim();

  writeFileSync(resolve(HTML_OUT, name + ".html"), body + "\n", "utf8");
  routes.push({ name, path: nameToPath(name), title });
}

// Stable order: home first, then alphabetical.
routes.sort((a, b) => (a.path === "/" ? -1 : b.path === "/" ? 1 : a.name.localeCompare(b.name)));

const manifest =
  "// AUTO-GENERATED by scripts/convert.mjs — do not edit by hand.\n" +
  "export const routes = " + JSON.stringify(routes, null, 2) + ";\n";
writeFileSync(resolve(OUT, "routes.js"), manifest, "utf8");

console.log(`Converted ${files.length} pages -> ${HTML_OUT}`);
console.log(routes.map((r) => `  ${r.path.padEnd(18)} ${r.name}.html`).join("\n"));
